create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  hwid text,
  hwid_reset_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product text not null check (product in ('cs2','csgo')),
  status text not null default 'inactive' check (status in ('inactive','active','expired','suspended')),
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.forum_topics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 120),
  body text not null check (char_length(body) between 3 and 10000),
  created_at timestamptz not null default now()
);

create table if not exists public.market_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 60),
  description text not null check (char_length(description) between 3 and 240),
  kind text not null check (kind in ('config','lua')),
  storage_path text not null unique,
  file_name text not null,
  file_size bigint not null check (file_size between 1 and 5242880),
  downloads integer not null default 0,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.subscriptions enable row level security;
alter table public.forum_topics enable row level security;
alter table public.market_items enable row level security;

create policy "profiles read own" on public.profiles for select using (auth.uid() = id);
create policy "profiles update own" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "subscriptions read own" on public.subscriptions for select using (auth.uid() = user_id);
create policy "forum public read" on public.forum_topics for select using (true);
create policy "forum create signed in" on public.forum_topics for insert with check (auth.uid() = user_id);
create policy "market public read" on public.market_items for select using (published = true or auth.uid() = user_id);
create policy "market create signed in" on public.market_items for insert with check (auth.uid() = user_id);
create policy "market delete own" on public.market_items for delete using (auth.uid() = user_id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('market', 'market', false, 5242880, array['text/plain','application/json','application/octet-stream'])
on conflict (id) do update set file_size_limit = excluded.file_size_limit;

create policy "market storage upload own" on storage.objects for insert to authenticated
with check (bucket_id = 'market' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "market storage read signed in" on storage.objects;
drop policy if exists "market storage read own or published" on storage.objects;
create policy "market storage read own or published" on storage.objects for select to authenticated using (
  bucket_id = 'market' and (
    (storage.foldername(name))[1] = auth.uid()::text
    or exists (select 1 from public.market_items item where item.storage_path = name and item.published = true)
  )
);
create policy "market storage delete own" on storage.objects for delete to authenticated
using (bucket_id = 'market' and (storage.foldername(name))[1] = auth.uid()::text);

create or replace function public.increment_market_download(item_id bigint)
returns void language sql security definer set search_path = public as $$
  update public.market_items set downloads = downloads + 1 where id = item_id and published = true;
$$;
grant execute on function public.increment_market_download(bigint) to authenticated;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1)));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
